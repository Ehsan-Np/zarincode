			$ids[ $key ] = $existing[0];
			continue;
		}

		$id = wp_insert_post(
			array(
				'post_type'    => 'zc_contract_tpl',
				'post_status'  => 'publish',
				'post_title'   => $tpl['title'],
				'post_content' => $tpl['content'],
				'meta_input'   => array(
					'_zc_demo'      => '1',
					'_zc_demo_key'  => $key,
					'_zc_ct_fields' => $tpl['fields'] ? implode( "\n", $tpl['fields'] ) : '',
					'_zc_ct_clauses' => $tpl['clauses'],
					'_zc_ct_notes'  => $tpl['notes'],
					'_zc_ct_amount' => $tpl['amount'],
					'_zc_ct_stages' => $tpl['stages'] ?? '',
					'_zc_ct_needs_spec' => ! empty( $tpl['needs_spec'] ) ? 1 : 0,
					'_zc_ct_public' => 1,
				),
			)
		);

		if ( ! is_wp_error( $id ) ) {
			$ids[ $key ] = $id;
		}
	}

	return $ids;
}
